// Builds supabase/demo-dataset.sql: the function public.demo_seed(), which adds the
// original fictional demo dataset. It is made from the same seed files a new project is
// set up with, so there is only one copy of the demo data. public.reset_demo_data() calls
// it after removing the demo records, on every page load in demo mode.
// Run with: npm run demo:generate   (after changing any seed file)
import { readFileSync, writeFileSync } from "node:fs";

/** Strip the transaction lines: the function runs inside the reset's own transaction. */
function body(file) {
  return readFileSync(file, "utf8")
    .split("\n")
    .filter((l) => !/^\s*(begin|commit);\s*$/i.test(l))
    .join("\n")
    .trim();
}

// From the catalogue, only the business's own demo choices. The HSC course list itself
// is reference data and is never reset.
const CATALOGUE_DEMO_START = "-- What the business offers.";
const catalogue = readFileSync("supabase/catalogue.sql", "utf8");
const at = catalogue.indexOf(CATALOGUE_DEMO_START);
if (at < 0) throw new Error(`supabase/catalogue.sql no longer has the line "${CATALOGUE_DEMO_START}". Update scripts/build-demo-dataset.mjs.`);

const parts = [
  ["supabase/seed.sql", body("supabase/seed.sql")],
  ["supabase/catalogue.sql (demo offerings, tutor and student courses)", catalogue.slice(at).trim()],
  ["supabase/demo-history.sql", body("supabase/demo-history.sql")],
  ["supabase/demo-classes.sql", body("supabase/demo-classes.sql")],
  ["supabase/demo-workflows.sql", body("supabase/demo-workflows.sql")],
];

for (const [name, sql] of parts) {
  if (sql.includes("$demo$")) throw new Error(`${name} uses the $demo$ quote, which this function needs.`);
}

const out = `-- Generated by scripts/build-demo-dataset.mjs (npm run demo:generate). Do not edit by hand.
-- The original fictional demo dataset, as one function. public.reset_demo_data() removes
-- the demo records and calls this to add them back, with dates worked out from today.
-- Safe to run more than once: it only replaces the function.

create or replace function public.demo_seed() returns void
language plpgsql as $demo$
begin
${parts.map(([name, sql]) => `-- ===== ${name} =====\n${sql}\n`).join("\n")}
end
$demo$;

revoke all on function public.demo_seed() from public, anon, authenticated;
`;

writeFileSync("supabase/demo-dataset.sql", out);
console.log(`Wrote supabase/demo-dataset.sql from ${parts.length} parts.`);
