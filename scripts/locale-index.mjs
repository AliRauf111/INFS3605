// Writes src/locales/<language>/index.ts, which joins that language's area files into one
// object. Run with: npm run i18n:index   (after adding an area file)
import { readdirSync, writeFileSync, existsSync } from "node:fs";

const root = "src/locales";
const areas = readdirSync(`${root}/en`).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5)).sort();
for (const lang of readdirSync(root, { withFileTypes: true }).filter((d) => d.isDirectory() && !d.name.startsWith("_")).map((d) => d.name)) {
  const present = areas.filter((a) => existsSync(`${root}/${lang}/${a}.json`));
  const name = (a) => a.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
  const lines = [
    "// Generated by scripts/locale-index.mjs. Do not edit by hand.",
    ...present.map((a) => `import ${name(a)} from "./${a}.json";`),
    "",
    `const ${lang === "en" ? "en" : "messages"} = { ${present.map(name).join(", ")} };`,
    `export default ${lang === "en" ? "en" : "messages"};`,
    "",
  ];
  writeFileSync(`${root}/${lang}/index.ts`, lines.join("\n"));
}
console.log(`Wrote index files for ${areas.length} areas.`);
