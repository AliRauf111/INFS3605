// Joins the migrations and seed files into supabase/setup-everything.sql, so a new
// Supabase project can be set up with one paste into the SQL Editor.
// Run with: npm run sql:bundle   (after changing any migration or seed file)
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const migrations = readdirSync("supabase/migrations").filter((f) => f.endsWith(".sql")).sort().map((f) => `supabase/migrations/${f}`);
const files = [...migrations, "supabase/seed.sql", "supabase/catalogue.sql", "supabase/demo-history.sql", "supabase/demo-classes.sql", "supabase/demo-workflows.sql", "supabase/demo-dataset.sql", "supabase/retention-demo.sql"];
const roles = `-- Give the two demo logins their roles. Create them first in Authentication > Users.
insert into public.app_users (id, display_name, role)
select id, 'Sarah Mitchell', 'admin' from auth.users where email = 'sarah@tutorcompass.example'
union all
select id, 'Alex Chen', 'owner' from auth.users where email = 'owner@tutorcompass.example'
on conflict (id) do update set display_name = excluded.display_name, role = excluded.role;
`;
const parts = files.map((f) => `-- ===== ${f} =====\n${readFileSync(f, "utf8").trim()}\n`);
const out = `-- Generated by scripts/bundle-sql.mjs. Do not edit by hand.
-- Paste this whole file into a NEW Supabase project's SQL Editor and click Run.
-- It creates the tables, adds fictional demo data and gives the demo logins their roles.

${parts.join("\n")}
${roles}`;
writeFileSync("supabase/setup-everything.sql", out);
console.log(`Wrote supabase/setup-everything.sql from ${files.length} files.`);
